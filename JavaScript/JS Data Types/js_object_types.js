// JavaScript Objects
{
  const person = {
    firstName: "Alberth",
    lastName: "Grande",
    age: 27,
    eyeColor: "brown",
  };
  console.log(
    `${person.firstName} ${person.lastName} is ${person.age} years old and has ${person.eyeColor} eyes.`,
  );
}

